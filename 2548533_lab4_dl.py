import numpy as np
from tensorflow.keras.datasets import mnist

"""#2. LOAD DATA"""

# Load dataset
(X_train, y_train), (X_test, y_test) = mnist.load_data()


X_train = X_train.astype(np.float32) / 255.0
X_test = X_test.astype(np.float32) / 255.0


X_train = X_train[:1000]
y_train = y_train[:1000]

print("Train shape:", X_train.shape)

"""#3. INITIALIZE PARAMETERS

"""

num_filters = 3
filter_size = 3

filters = np.random.randn(num_filters, filter_size, filter_size) * 0.1

# After conv + pooling:
# Input 28x28 → conv (26x26) → pool (13x13)
# With 3 filters → output = 3 × 13 × 13 = 507 features


fc_input_size = num_filters * 13 * 13
fc_output_size = 10

W_fc = np.random.randn(fc_input_size, fc_output_size) * 0.1
b_fc = np.zeros(fc_output_size)

print("Filters shape:", filters.shape)
print("FC weights shape:", W_fc.shape)

"""#4. CONVOLUTION FORWARD"""

def conv_forward(image, filters):
    num_filters, f, _ = filters.shape
    h, w = image.shape

    out_h = h - f + 1
    out_w = w - f + 1

    output = np.zeros((num_filters, out_h, out_w))

    for n in range(num_filters):
        for i in range(out_h):
            for j in range(out_w):
                region = image[i:i+f, j:j+f]
                output[n, i, j] = np.sum(region * filters[n])

    return output

test_conv = conv_forward(X_train[0], filters)
print("Conv output shape:", test_conv.shape)

"""#5. RELU ACTIVATION"""

def relu(feature_map):
    return np.maximum(0, feature_map)

# Test ReLU
test_relu = relu(test_conv)
print("ReLU output shape:", test_relu.shape)

"""#6. MAX POOLING"""

def max_pool(feature_map, size=2):
    num_filters, h, w = feature_map.shape
    out_h = h // size
    out_w = w // size

    pooled = np.zeros((num_filters, out_h, out_w))

    for n in range(num_filters):
        for i in range(out_h):
            for j in range(out_w):
                region = feature_map[n,
                                     i*size:(i+1)*size,
                                     j*size:(j+1)*size]
                pooled[n, i, j] = np.max(region)

    return pooled

# Test pooling
test_pool = max_pool(test_relu)
print("Pooling output shape:", test_pool.shape)

"""#7. FLATTEN LAYER"""

def flatten(feature_map):
    return feature_map.reshape(-1)

# Test flatten
test_flat = flatten(test_pool)
print("Flatten size:", test_flat.shape)

"""#8. FULLY CONNECTED FORWARD"""

def fc_forward(x, W, b):
    return np.dot(x, W) + b

# Test FC forward
test_fc = fc_forward(test_flat, W_fc, b_fc)
print("FC output shape:", test_fc.shape)

"""#9. SOFTMAX FUNCTION"""

def softmax(x):
    exp_x = np.exp(x - np.max(x))  # stability trick
    return exp_x / np.sum(exp_x)

# Test softmax
test_probs = softmax(test_fc)
print("Probabilities sum:", np.sum(test_probs))

"""#10. CROSS ENTROPY LOSS"""

def cross_entropy_loss(probs, label):
    return -np.log(probs[label] + 1e-9)

# Test loss
test_loss = cross_entropy_loss(test_probs, y_train[0])
print("Loss:", test_loss)

"""#11. BACK PROPOGATION




"""

def fc_backward(x, probs, label, W):
    # One-hot encode label
    y_onehot = np.zeros_like(probs)
    y_onehot[label] = 1

    # Gradient of loss w.r.t. scores
    dL_dz = probs - y_onehot

    # Gradients
    dW = np.outer(x, dL_dz)
    db = dL_dz

    return dW, db

"""#12. TRAINING LOOP"""

learning_rate = 0.01
epochs = 20

for epoch in range(epochs):
    total_loss = 0

    for i in range(len(X_train)):
        image = X_train[i]
        label = y_train[i]

        # Forward pass
        conv_out = conv_forward(image, filters)
        relu_out = relu(conv_out)
        pool_out = max_pool(relu_out)
        flat = flatten(pool_out)
        fc_out = fc_forward(flat, W_fc, b_fc)
        probs = softmax(fc_out)
        loss = cross_entropy_loss(probs, label)

        total_loss += loss

        # Backprop (FC layer only)
        dW, db = fc_backward(flat, probs, label, W_fc)

        # Update weights
        W_fc -= learning_rate * dW
        b_fc -= learning_rate * db

    print(f"Epoch {epoch+1}, Loss: {total_loss:.2f}")

"""#13. TESTING"""

correct = 0

for i in range(len(X_test[:200])):
    image = X_test[i]
    label = y_test[i]

    conv_out = conv_forward(image, filters)
    relu_out = relu(conv_out)
    pool_out = max_pool(relu_out)
    flat = flatten(pool_out)
    fc_out = fc_forward(flat, W_fc, b_fc)
    probs = softmax(fc_out)

    prediction = np.argmax(probs)

    if prediction == label:
        correct += 1

accuracy = correct / 200 * 100
print(f"Accuracy on test subset: {accuracy:.2f}%")

